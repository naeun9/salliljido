// 파일럿 지역 단일 소스.
//
// 29곳 모두 행정안전부가 지정한 인구감소지역이다(「지방자치분권 및 지역균형
// 발전에 관한 특별법」 제2조, 2021년 10월 최초 지정, 5년 단위). 관심지역과
// 미지정 지역은 넣지 않는다 — 화면 곳곳의 "인구감소지역" 배지가 조건 없이
// 붙기 때문에(components/region/RegionCard.jsx 등) 목록에 관심지역이 섞여
// 있으면 그 배지가 틀린 말이 된다. 지역을 더할 때도 같은 기준을 지킬 것.
//
// 왜 광역별로 10/9/10곳인가: 지역 찾기 조건은 광역 3 × 라이프스타일 4 =
// 12가지인데, 추천 결과는 3곳까지 보여 준다(services/regionRecommend.js의
// slice(0, 3)). 그래서 조합마다 후보가 3곳은 있어야 카드가 빈자리 없이
// 찬다. 15곳이던 때는 강원×소도시·충남×산·경북×바다가 각각 1곳뿐이었다.
// 충남이 9곳인 것은 충청남도 인구감소지역이 9곳이 전부이기 때문이다.
//
// 바다는 지리적 상한이 있다. 인구감소지역 중 바다에 접한 곳은 광역별로
// 정확히 3곳씩뿐이라(강원 양양·고성·삼척, 충남 태안·서천·보령,
// 경북 영덕·울진·울릉) 이 아홉 곳은 목록에서 뺄 수 없다.
//
// places는 [주분류, 부분류]다. 추천이 places.indexOf(고른 라이프스타일)로
// 정렬하므로 주분류로 적힌 지역이 결과 앞자리에 온다. 분류는 감이 아니라
// 관광공사 분류체계 건수로 잡았다 — 바다는 해변·해안절경·항구·섬(NA02),
// 산은 산·계곡·폭포·휴양림·국립공원(NA01/NA04) 건수를 기준으로 했고,
// 이 지표로 기존 15곳의 분류가 그대로 재현되는 것을 확인한 뒤 적용했다.
//
// 목록이 길어져 광역별 파일로 나눴다(CLAUDE.md 300줄 규칙). 지역을
// 추가·수정할 때는 regions/ 아래 해당 광역 파일만 고치면 된다.
//
// 예전에는 이 목록이 두 곳에 나뉘어 있었다 — services/regionRecommend.js의
// REGION_POOL(추천용 정보)과 data/regionCodes.js의 REGION_LDONG_CODES
// (관광공사 조회용 법정동 코드). 같은 지역을 각자 들고 있어서 한쪽에만
// 지역을 추가하면 추천에는 뜨는데 둘러보기가 "법정동 코드가 없습니다"로
// 죽었다. 그래서 한 곳으로 합쳤다 — 조회용 코드와 추천용 정보가 늘 같이 온다.
//
// 필드 구분:
//   - 식별/조회용(계속 유지): region, name, short, regnCd, signguCd
//     regnCd/signguCd는 관광공사 TourAPI의 법정동 코드다. 예전 areaCode
//     방식은 폐기됐고(docs/03-api-check.md §2) ldongCode2로 직접 조회해
//     확인한 값이다. 행정구역 코드라 거의 바뀌지 않는 정적 참조표이며,
//     관광 콘텐츠가 아니므로 "실시간 호출" 규칙과 무관하다.
//   - access — 지역 소개의 "교통 접근" 한 줄. 29곳 전부 적어 두었다.
//     예전에는 지역명 해시로 "고속버스와 기차로 2시간" / "버스 위주라…"
//     두 문장 중 하나를 골랐는데, 철도가 없는 군이나 배로만 닿는 울릉에서는
//     틀린 말이 나갔다. 지금은 수도권(서울) 출발 기준으로 주된 수단과
//     대략의 소요시간을 적는다. 시간을 확인하지 못한 곳은 단정하지 않고
//     수단만 적었다(영덕·울진·청도). 철도는 노선이 늘고 줄기 때문에,
//     시간표가 바뀌면 이 값도 같이 손봐야 한다.
//   - visitors — 하루 평균 방문자 수(외지인+외국인). 한국관광 데이터랩
//     빅데이터 지역별 방문자수(api/tour/visitors.js)로 2025-08~2026-07의
//     달마다 수요일·토요일 하루씩 24일을 재어 평균 낸 값이다. 계절과 요일이
//     한쪽으로 쏠리지 않게 그렇게 골랐다. "한적함"이 이 값으로 갈린다.
//     상류가 일별만 주고 시군구로 좁혀지지도 않아(하루치 전국 807건이
//     통째로 온다) 화면에서 그때그때 부르면 하루 한도를 태운다. 그래서
//     한 번 재어 여기 적어 둔다 — lat/lng·counts와 같은 성격의 정적 참조값.
//   - counts / theme — 그 지역 관광공사 목록(areaBasedList2) 실측값이다.
//     total(전체) · stay(숙박 AC) · food(식사류, FD에서 카페 FD05를 뺀 수) ·
//     cafe(카페 FD05), theme는 관광지 네 갈래(자연·역사·문화·레저) 중
//     뚜렷하게 많은 쪽이고 1·2위가 한두 건 차이면 "혼합"이다.
//     2026-09-10에 한 번 재어 적었다. 지역 소개 문구와 추천 결과 게이지가
//     이 값으로 갈린다(services/regionProfile.js) — 예전에는 두 화면이
//     각자 지역명 해시로 점수를 만들어 실제와 무관한 말을 했다.
//     관광 콘텐츠 캐시가 아니라 lat/lng·regnCd와 같은 성격의 정적 참조값
//     이지만, 원본이 늘고 줄면 구간이 바뀔 수 있어 가끔 다시 재야 한다.
//   - 추천 목업용(실제 API로 교체되면 사라질 값): places, reason, tags,
//     lat, lng, imageNote — services/regionRecommend.js 상단 주석 참고.
//     lat/lng는 그 지역 관광 목록(areaBasedList2) 좌표의 중앙값을 한 번
//     계산해 적어 둔 값이다. 지도의 시작 중심점을 잡는 데만 쓰는 좌표
//     한 쌍이고 관광 콘텐츠가 아니므로 "실시간 호출" 규칙과 무관하다
//     (regnCd/signguCd와 같은 성격의 정적 참조값). 평균이 아니라
//     중앙값인 이유는 태안처럼 섬이 멀리 있으면 평균이 바다로 끌려가서다.
import { GANGWON } from "./regions/gangwon.js";
import { CHUNGNAM } from "./regions/chungnam.js";
import { GYEONGBUK } from "./regions/gyeongbuk.js";

// 광역 순서(강원 → 충남 → 경북)와 광역 안의 순서를 그대로 이어 붙인다.
// 추천 정렬은 주분류 우선이고 같은 순위끼리는 이 배열 순서를 따르므로,
// 순서를 바꾸면 결과 화면에 뜨는 3곳이 바뀐다.
export const REGIONS = [...GANGWON, ...CHUNGNAM, ...GYEONGBUK];

// short(지역 slug) → 지역 레코드. 조회가 잦아 미리 만들어 둔다.
export const REGION_BY_SHORT = Object.fromEntries(REGIONS.map((r) => [r.short, r]));
