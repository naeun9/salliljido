//
// 공식 공고 URL은 되도록 채우되, 없어도 신청 기간이 확인됐으면 넣는다
// (url을 비우면 카드가 "공고 확인 필요 · 문의처로 확인해 주세요"를
// 보여 준다). 제3자 집계 서비스(한달러 등) 링크는 url에 넣지 않는다 —
// 공고 원문이 아니라 재가공된 정보라 신청 근거가 될 수 없다.
//
// 신청 기간을 못 채우면 아예 넣지 않는 이유: 상태(모집 중/예정/마감)가
// start·end에서 자동으로 나오기 때문에, 둘 다 비워 두면 이미 끝난 사업이
// "상시 모집"으로 표시된다.
//
// ─────────────────────────────────────────────────────────────
// 넣지 못한 것 — 다시 찾아볼 때 같은 길을 되짚지 않도록
// ─────────────────────────────────────────────────────────────
//   - 그린대로(greendaero.go.kr) "농촌에서 살아보기" 마을 상세 링크
//     전부(양양·삼척·정선·평창·홍천·영월·청도): 상세 페이지가 마을
//     정보를 서버에서 내려주지 않는다. vlgMngno를 바꿔도 응답 HTML이
//     똑같고, 날짜 자리가 "20YY.MM.DD" 플레이스홀더인 춘천 은행나무마을
//     견본만 나온다. 그 URL을 신청 링크로 걸면 방문자가 엉뚱한 마을을
//     보게 된다. 시군 공식 공고를 따로 찾은 봉화만 넣었다.
//   - 양양 "2026년 양양에서 살아보기": 2개월·10명(2기수)·숙식 및 운영
//     260만 원 상당·보증금 30만 원까지 확인했지만, 접수가 4월 중
//     그린대로로만 열려 신청 기간 시작·종료일을 확인하지 못했다.
//   - 삼척 "2026년 하반기 강원에서 살아보기": 원덕읍 산양마을, 귀농형
//     5가구 7명, 운영 9.1~11.30, 모집 마감 8.20까지는 확인됐으나 모집
//     시작일과 삼척시 공식 공고 페이지를 찾지 못했다.
//   - 평창 "강원에서 살아보기": pc.go.kr 고시공고 37252는 2024년 2기
//     공고다(모집 2024.9.23~10.7). 2026년 공고를 찾지 못했다.
//   - 정선·홍천: 그린대로에 마을은 있으나 2026년 모집 공고가 없다.
//   - 강원 고성: 조사 목록의 한달러 링크가 실제로는 경상남도 고성군
//     "힐링해 고성 여행지원금"이다. 파일럿 29곳의 강원 고성군이 아니다.
//   - 청도 "2026년 농촌에서 살아보기": 1기(운영 5.18~6.17)·2기 운영
//     사실은 보도로 확인되나 청도군 모집 공고를 찾지 못했다.
//   - 울진 "울진애고백": 체류 프로그램이 아니라 관내 사용액 10%를
//     상품으로 돌려주는 소비 환급 사업이고, 공고도 2025년 것이다.
//   - 안동·금산·공주·청양·철원·태백·화천·영주·울릉·문경·청송: 2026년
//     체류지원 공고를 확인하지 못했다.
//   - 보령 하반기(모집 8.18~8.31, 여행 9.18~11.30, 15팀): 보도로만
//     확인되고 공고 URL을 못 잡아 상반기 공고만 넣었다.
//
//   ※ 의성 "농촌에서 살아보기 일산자두골마을 3기"는 공식 공고 URL만
//     못 찾아, url을 비운 채로 넣었다. 기준을 무르게 한 것이 아니라
//     신청 기간이 확인됐기 때문이다 — 상태 자동 판정이 틀리지 않는다.
//     url이 비면 카드가 "신청 페이지로 이동" 대신 "공고 확인 필요"를
//     보여 준다. 자세한 사유는 supportPrograms/gyeongbuk.js 주석 참고.
//
// ─────────────────────────────────────────────────────────────
// 입력 양식 — 한 건을 추가할 때 이 블록을 복사해서 채우면 된다.
// ─────────────────────────────────────────────────────────────
//   {
//     id: "",          // 영문 소문자 식별자. 다른 항목과 겹치면 안 된다.
//                      //   예: "taean-week-2026", "yeongwol-live-2026"
//                      //   ※ 관심 등록이 이 값으로 저장되므로 한 번 정하면 바꾸지 말 것.
//     type: PROGRAM_TYPE.STAY_TRIP,  // 또는 PROGRAM_TYPE.RURAL_LIFE
//                      //   뜻은 supportPrograms/types.js 참고.
//     name: "",        // 공고에 적힌 사업명 그대로.  예: "2026 부여 한달살기 관광"
//     city: "",        // "시도 시군구" 형식.  예: "충남 태안군", "경북 영덕군"
//                      //   ※ 앞 두 글자로 지역 필터(강원/충남/경북)가 자동으로 정해진다.
//                      //   ※ data/regions의 파일럿 29곳 표기와 똑같이 적을 것.
//     benefits: [],    // 지원 내용을 항목별로 나눠 적는다(문장 하나씩).
//                      //   예: ["숙박비 팀당 1박 5만 원 이내",
//                      //        "체험활동비 1인 10만 원"]
//                      //   ※ 카드에는 " · "로 이어 붙여 한 줄로 보인다.
//     start: "",       // 신청 시작일 "YYYY-MM-DD".
//     end: "",         // 신청 마감일 "YYYY-MM-DD". 선착순·상시 모집이면 null.
//     target: "",      // 모집 대상.  예: "충남 외 거주 만 19세 이상"
//     quota: "",       // 모집 인원.  예: "25팀 이내", "8가구 (16명)", "선착순"
//     stayWeeks: "",   // 요구 체류 기간. 여행·운영 기간도 괄호로 함께 적는다.
//                      //   예: "6박 7일 (여행 4.20~5.31)"
//     contact: "",     // 문의처 전화번호.  예: "041-746-5152"
//     url: "",         // 공고·신청 페이지 주소(https:// 부터).
//     posted: "",      // 공고 게시일 "YYYY-MM-DD". "최근 등록순" 정렬에 쓴다.
//     checkedAt: "",   // 이 내용을 마지막으로 확인한 날짜 "YYYY-MM-DD".
//   },
//
// target·quota·stayWeeks·contact·posted·url은 확인 못 하면 ""로 둔다.
// 카드에서 그 칸이 통째로 빠진다 — 추측해서 채우지 말 것.
