// 배지에 쓸 짧은 이름. design의 배지는 "펜션·민박", "해변"처럼 짧아서,
// 코드표의 긴 이름에서 목록 구분자 뒤를 잘라낸다.
//   "카페/ 찻집" → "카페", "산, 고개, 오름, 봉우리" → "산",
//   "해변. 해수욕장" → "해변"
// 마침표는 뒤에 공백이 있을 때만 구분자로 본다 — "농.산.어촌 체험"처럼
// 마침표가 이름 자체에 붙어 있는 경우를 자르면 안 되기 때문이다.
export function shortTypeName(lclsSystm3) {
  const full = LCLS3_NAMES[lclsSystm3];
  if (!full) return "";
  return full.split(/[,/]|\.\s/)[0].trim();
}
